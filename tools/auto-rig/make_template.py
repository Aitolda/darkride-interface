"""Write the standard skeleton table (Mixamo's T-pose from Beta, eyes placed from the mannequin's head) as C++."""
import json, sys
beta = {r["name"]: r for r in json.load(open(sys.argv[1]))}
man = {r["name"]: r for r in json.load(open(sys.argv[2]))}
FINGERS = ["Thumb", "Index", "Middle", "Ring", "Pinky"]
order, parent = [], {}
def add(name, par):
    order.append(name); parent[name] = par
add("Hips", None)
for side in ("Left", "Right"):
    prev = "Hips"
    for j in ("UpLeg", "Leg", "Foot", "ToeBase", "Toe_End"):
        add(side + j, prev); prev = side + j
prev = "Hips"
for j in ("Spine", "Spine1", "Spine2"):
    add(j, prev); prev = j
for side in ("Left", "Right"):
    prev = "Spine2"
    for j in ("Shoulder", "Arm", "ForeArm", "Hand"):
        add(side + j, prev); prev = side + j
    for f in FINGERS:
        prev = side + "Hand"
        for k in range(1, 5):
            add(f"{side}Hand{f}{k}", prev); prev = f"{side}Hand{f}{k}"
add("Neck", "Spine2"); add("Head", "Neck"); add("HeadTop_End", "Head"); add("LeftEye", "Head"); add("RightEye", "Head")
# eyes: the mannequin's eye offsets from its head, scaled by head height, put on Beta's head
def v(r): return r["abs"]["t"]
mh, mt = v(man["Head"]), v(man["HeadTop_End"])
bh, bt = v(beta["Head"]), v(beta["HeadTop_End"])
k = (bt[1] - bh[1]) / (mt[1] - mh[1])
eyes = {}
for e in ("LeftEye", "RightEye"):
    me = v(man[e])
    eyes[e] = [bh[0] + (me[0] - mh[0]) * k, bh[1] + (me[1] - mh[1]) * k, bh[2] + (me[2] - mh[2]) * k]
half = (abs(eyes["LeftEye"][0] - bh[0]) + abs(eyes["RightEye"][0] - bh[0])) / 2  # the mannequin's head is off-centre: make them symmetric
mid = [(eyes["LeftEye"][i] + eyes["RightEye"][i]) / 2 for i in (1, 2)]
eyes["LeftEye"] = [bh[0] + half, mid[0], mid[1]]; eyes["RightEye"] = [bh[0] - half, mid[0], mid[1]]
out = ["// Generated by make_template.py from Mixamo's Beta (T-pose, cm) and the default avatar's eyes. Do not edit by hand.",
       "static const TemplateJoint STANDARD_JOINTS[] = {"]
for n in order:
    if n in eyes:
        t, r = eyes[n], beta["Head"]["abs"]["r"]
    else:
        t, r = beta[n]["abs"]["t"], beta[n]["abs"]["r"]
    p = parent[n]
    out.append('    { "%s", %s, { %.4ff, %.4ff, %.4ff }, { %.6ff, %.6ff, %.6ff, %.6ff } },' % (
        n, ('"%s"' % p) if p else "nullptr", t[0], t[1], t[2], r[3], r[0], r[1], r[2]))
out.append("};")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
print(len(order), "joints; eyes at", [[round(c, 1) for c in eyes[e]] for e in eyes])
